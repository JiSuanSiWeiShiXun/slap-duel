import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { projectPath } from './bootstrap-game.mjs';
import { verifyBuild } from './check-game.mjs';
import { selectPublicFiles, stageRelease, verifyRelease } from './package-web-release.mjs';

test('actual Cocos release roundtrip excludes source maps/private files and detects tampering', () => {
  const root = projectPath(`game/local/release-tests/${Date.now()}-${process.pid}`);
  const source = path.join(root, 'source');
  const stage = path.join(root, 'release');
  const extracted = path.join(root, 'extracted');
  const build = verifyBuild('web-desktop');
  fs.mkdirSync(root, { recursive: true });
  fs.cpSync(projectPath('game/build/web-desktop'), source, { recursive: true });
  assert.ok(fs.readdirSync(path.join(source, 'src')).some(name => name.endsWith('.map')));
  fs.writeFileSync(path.join(source, '.env'), 'PRIVATE_TEST_SENTINEL=never-publish');
  assert.throws(() => selectPublicFiles(source), /Unsafe release path/);
  fs.unlinkSync(path.join(source, '.env'));
  fs.writeFileSync(path.join(source, 'credentials.json'), '{"private":"never-publish"}');
  assert.throws(() => selectPublicFiles(source), /Unexpected file/);
  fs.unlinkSync(path.join(source, 'credentials.json'));
  const staged = stageRelease(source, stage, build);
  assert.equal(staged.buildId, build.buildId);
  assert.ok(staged.fileCount > 20);
  assert.equal(fs.existsSync(path.join(stage, 'site/cocos-js/cc.js.map')), false);
  assert.equal(fs.existsSync(path.join(stage, 'site/.env')), false);
  const archive = path.join(root, 'roundtrip.tar.gz');
  execFileSync('tar', ['-czf', archive, '-C', stage, 'site', 'release-manifest.json', 'SHA256SUMS']);
  fs.mkdirSync(extracted);
  execFileSync('tar', ['-xzf', archive, '-C', extracted]);
  assert.deepEqual(verifyRelease(extracted), staged);
  const original = fs.readFileSync(path.join(extracted, 'site/index.js'));
  fs.appendFileSync(path.join(extracted, 'site/index.js'), '\n/* unintended change */');
  assert.throws(() => verifyRelease(extracted), /Checksum mismatch/);
  fs.writeFileSync(path.join(extracted, 'site/index.js'), original);
  fs.writeFileSync(path.join(extracted, 'site/private.txt'), 'not in manifest');
  assert.throws(() => verifyRelease(extracted), /unexpected files/);
  assert.throws(() => stageRelease(source, stage, build), /never overwrite/);
});
