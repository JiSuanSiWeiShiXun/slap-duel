import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { ROOT, IDS, checkConfig, projectPath } from './bootstrap-game.mjs';

function entries(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const target = projectPath(path.relative(ROOT, path.join(directory, entry.name)));
    return entry.isDirectory() ? entries(target) : [target];
  }).sort();
}

function digestSources(excludeBuildInfo = false, sourceRoot = ROOT) {
  const root = projectPath(path.relative(ROOT, path.resolve(sourceRoot)));
  const hash = crypto.createHash('sha256');
  const buildInfo = path.join(root, 'game/assets/scripts/BuildInfo.ts');
  for (const file of [...entries(path.join(root, 'game/assets')), ...entries(path.join(root, 'game/build-config')),
    ...entries(path.join(root, 'game/build-templates')), ...entries(path.join(root, 'game/settings')), path.join(root, 'game/package.json')]) {
    if (excludeBuildInfo && file === buildInfo) continue;
    const relative = path.relative(root, file).replaceAll('\\', '/');
    // Creator regenerates this editor account/form metadata during startup; it
    // is not a game build input and must remain private even when absent at prepare.
    if (relative === 'game/settings/v2/packages/information.json') continue;
    hash.update(relative);
    hash.update(fs.readFileSync(file));
  }
  return hash.digest('hex');
}

export function sourceDigest(sourceRoot = ROOT) { return digestSources(false, sourceRoot); }

function preparedPath(target) {
  targetDirectory(target);
  return projectPath(`game/local/prepared-${target}.json`);
}

function processAlive(pid) {
  if (!Number.isSafeInteger(pid) || pid <= 0) return true;
  try { process.kill(pid, 0); return true; } catch (error) { return error.code !== 'ESRCH'; }
}

function claimPreparation(target) {
  const file = preparedPath(target);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (fs.existsSync(file)) {
    const prior = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (processAlive(prior.ownerPid)) throw new Error(`Build preparation already active for ${target} (PID ${prior.ownerPid})`);
    fs.unlinkSync(file); // An abandoned build may be retried; never replace a live build's snapshot.
  }
  const snapshot = { target, ownerPid: process.ppid, nonce: crypto.randomUUID(), preparedAt: new Date().toISOString() };
  fs.writeFileSync(file, JSON.stringify(snapshot), { flag: 'wx' });
  return { file, snapshot };
}

export function prepareBuild(target) {
  targetDirectory(target);
  checkConfig();
  const claim = claimPreparation(target);
  try {
  const fingerprint = digestSources(true);
  const sessionPath = projectPath('game/local/build-session.json');
  let previous;
  try { previous = JSON.parse(fs.readFileSync(sessionPath, 'utf8')); } catch { /* First build or an invalid local cache. */ }
  const reused = previous?.fingerprint === fingerprint && typeof previous.buildId === 'string' && /^P1-[a-f0-9]+-[a-f0-9]{8}-[0-9TZ]+$/.test(previous.buildId);
  const revision = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: ROOT, encoding: 'utf8' }).trim();
  const buildId = reused ? previous.buildId : `P1-${revision}-${fingerprint.slice(0, 8)}-${new Date().toISOString().replace(/[-:.]/g, '')}`;
  const infoPath = projectPath('game/assets/scripts/BuildInfo.ts');
  const source = `// Generated by tools/build-game.ps1; shared across targets with identical source inputs.\nexport const BUILD_ID = ${JSON.stringify(buildId)};\n`;
  if (!fs.existsSync(infoPath) || fs.readFileSync(infoPath, 'utf8') !== source) fs.writeFileSync(infoPath, source);
  fs.mkdirSync(path.dirname(sessionPath), { recursive: true });
  if (!reused) fs.writeFileSync(sessionPath, JSON.stringify({ fingerprint, buildId, revision }, null, 2) + '\n');
  fs.writeFileSync(claim.file, JSON.stringify({ ...claim.snapshot, fingerprint, buildId, revision, sourceDigest: sourceDigest() }, null, 2) + '\n');
  return { target, buildId, reused };
  } catch (error) {
    fs.unlinkSync(claim.file);
    throw error;
  }
}

function targetDirectory(target) {
  if (!['web-desktop', 'wechatgame'].includes(target)) throw new Error(`Unknown target: ${target}`);
  return projectPath(`game/build/${target}`);
}

function verifyFiles(target) {
  checkConfig();
  if (!fs.existsSync(projectPath('game/assets/scripts/SlapGame.ts'))) throw new Error('SlapGame.ts has not been implemented');
  const directory = targetDirectory(target);
  const entry = path.join(directory, target === 'web-desktop' ? 'index.html' : 'game.js');
  if (!fs.existsSync(entry)) throw new Error(`Build missing: ${entry}`);
  if (!fs.existsSync(path.join(directory, 'src'))) throw new Error('Build script directory missing');
  return directory;
}

function currentBuildId() {
  const source = fs.readFileSync(projectPath('game/assets/scripts/BuildInfo.ts'), 'utf8');
  return source.match(/BUILD_ID\s*=\s*["']([^"']+)["']/)?.[1];
}

export function artifactContainsBuildId(directory, buildId) {
  if (typeof buildId !== 'string' || !/^P1-[a-f0-9]+-[a-f0-9]{8}-[0-9TZ]+$/.test(buildId)) return false;
  // Only executable bundle content counts: not a manifest, source map, or copied source file.
  return entries(directory).filter(file => file.endsWith('.js')).some(file => {
    const code = fs.readFileSync(file, 'utf8');
    return code.includes(JSON.stringify(buildId)) || code.includes(`'${buildId}'`);
  });
}

export function assertPreparedBuild(target, prepared, current, embedded) {
  if (prepared?.target !== target || !prepared.nonce || !prepared.revision || !prepared.preparedAt || !prepared.sourceDigest || !prepared.fingerprint) throw new Error('Missing prepared build snapshot');
  if (prepared.buildId !== current.buildId) throw new Error('BuildInfo changed during compilation; rebuild required');
  if (prepared.fingerprint !== current.fingerprint || prepared.sourceDigest !== current.sourceDigest) throw new Error('Build inputs changed during compilation (including imported metadata/settings); prepare and rebuild again');
  if (!embedded) throw new Error('Compiled JavaScript does not contain the prepared build ID');
}

export function stampBuild(target) {
  const directory = verifyFiles(target);
  const file = preparedPath(target);
  const prepared = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (prepared.ownerPid !== process.ppid) throw new Error('Only the preparing build process may stamp this target');
  assertPreparedBuild(target, prepared, { buildId: currentBuildId(), fingerprint: digestSources(true), sourceDigest: sourceDigest() }, artifactContainsBuildId(directory, prepared.buildId));
  const manifest = { target, engine: '3.8.8', revision: prepared.revision, buildId: prepared.buildId, scene: IDS.scene,
    sourceDigest: prepared.sourceDigest, inputFingerprint: prepared.fingerprint, preparedAt: prepared.preparedAt, builtAt: new Date().toISOString() };
  fs.writeFileSync(path.join(directory, 'build-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  fs.unlinkSync(file);
  return manifest;
}

export function verifyBuild(target) {
  const directory = verifyFiles(target);
  const manifest = JSON.parse(fs.readFileSync(path.join(directory, 'build-manifest.json'), 'utf8').replace(/^\uFEFF/, ''));
  if (manifest.target !== target || manifest.engine !== '3.8.8' || manifest.scene !== IDS.scene) throw new Error('Build identity mismatch');
  if (manifest.sourceDigest !== sourceDigest()) throw new Error('Build is stale; source files changed after the build');
  if (!artifactContainsBuildId(directory, manifest.buildId)) throw new Error('Compiled JavaScript build identity mismatch');
  if (!manifest.revision || !Number.isFinite(Date.parse(manifest.builtAt))) throw new Error('Missing build provenance');
  return manifest;
}

export function typecheckGame() {
  const engine = process.env.COCOS_ENGINE || 'E:/DevTools/CocosCreator/3.8.8/resources/resources/3d/engine';
  const declaration = path.join(engine, 'bin/.declarations/cc.d.ts');
  const compiler = path.join(engine, 'node_modules/typescript/bin/tsc');
  if (!fs.existsSync(declaration) || !fs.existsSync(compiler)) throw new Error('Real Cocos declarations/compiler missing; set COCOS_ENGINE to the installed 3.8.8 engine');
  const config = projectPath('game/local/tsconfig.check.json');
  fs.mkdirSync(path.dirname(config), { recursive: true });
  fs.writeFileSync(config, JSON.stringify({
    compilerOptions: { target: 'ES2020', module: 'commonjs', strict: true, noEmit: true,
      experimentalDecorators: true, useDefineForClassFields: false, skipLibCheck: true,
      lib: ['ES2020', 'DOM'], types: [] },
    files: [declaration, ...entries(projectPath('game/assets/scripts')).filter(file => file.endsWith('.ts'))],
  }, null, 2));
  execFileSync(process.execPath, [compiler, '--project', config, '--pretty', 'false'], { cwd: ROOT, stdio: 'inherit' });
  return { status: 'passed', declaration, compiler };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    if (args.length === 1 && args[0] === '--config-only') console.log(JSON.stringify(checkConfig(), null, 2));
    else if (args.length === 1 && args[0] === '--typecheck') console.log(JSON.stringify(typecheckGame(), null, 2));
    else if (args.length === 2 && args[0] === '--target') console.log(JSON.stringify(verifyBuild(args[1]), null, 2));
    else if (args.length === 2 && args[0] === '--stamp') console.log(JSON.stringify(stampBuild(args[1]), null, 2));
    else if (args.length === 2 && args[0] === '--prepare') console.log(JSON.stringify(prepareBuild(args[1]), null, 2));
    else throw new Error('Usage: node tools/check-game.mjs --config-only | --typecheck | --target TARGET | --prepare TARGET | --stamp TARGET');
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
